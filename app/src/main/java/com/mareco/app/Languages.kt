    val english: Language get() = all[0]

    fun byTag(tag: String?): Language? = if (tag.isNullOrEmpty()) null else all.firstOrNull { it.tag == tag }

    /**
     * Which of our languages a phone locale maps to. Android still reports a few old language codes
     * (iw, in, ji, tl) on some versions, and Chinese / Portuguese come in two flavours.
     * Falls back to English when the phone's language is not translated (that is what Android shows then too).
     */
    fun match(language: String, script: String?, country: String?): Language {
        val lang = when (language) {
            "iw" -> "he"
            "in" -> "id"
            "tl" -> "fil"
            "no", "nn" -> "nb"
            else -> language
        }
        if (lang == "zh") {
            val traditional = script == "Hant" || country == "TW" || country == "HK" || country == "MO"
            return byTag(if (traditional) "zh-TW" else "zh-CN") ?: english
        }
        if (lang == "pt") return byTag(if (country == "PT") "pt-PT" else "pt-BR") ?: english
        return all.firstOrNull { it.tag == lang } ?: english
    }
