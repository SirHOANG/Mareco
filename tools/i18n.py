#!/usr/bin/env python3
"""
Mareco translation helper.

The English texts live in app/src/main/res/values/strings.xml. Every language has its own folder
app/src/main/res/values-<qualifier>/strings.xml (the list of languages is tools/languages.tsv).

Workflow (works the same for a human translator or a machine translator):

  python3 tools/i18n.py source            write  <work>/source.tsv   (number, key, English text, note)
  ... translate: write <work>/out/<tag>.tsv   one line per string:  <number> TAB <translation>
  python3 tools/i18n.py check  vi         validate <work>/out/vi.tsv against the English source
  python3 tools/i18n.py build  vi         write app/src/main/res/values-vi/strings.xml  (only if check passes)
  python3 tools/i18n.py audit             check every values-*/strings.xml that exists against the master list
  python3 tools/i18n.py sync              copy the languages that have a values-<q>/strings.xml into Languages.kt and
                                          res/xml/locales_config.xml (so the language list only offers real translations)

<work> defaults to tools/work next to this script (override with --work DIR; only `source`, `check` and `build` use it). Texts keep \\n for a new line, and every
%s / %1$s / %2$s placeholder of the English text, exactly once per occurrence.
"""
import argparse
import os
import re
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
RES = os.path.join(ROOT, 'app', 'src', 'main', 'res')
LANGS_KT = os.path.join(ROOT, 'app', 'src', 'main', 'java', 'com', 'mareco', 'app', 'Languages.kt')
LOCALES_XML = os.path.join(RES, 'xml', 'locales_config.xml')
MASTER = os.path.join(ROOT, 'tools', 'languages.tsv')
KT_BEGIN = '        // <languages: generated by tools/i18n.py sync>'
KT_END = '        // </languages>'
SRC_XML = os.path.join(RES, 'values', 'strings.xml')

PLACEHOLDER = re.compile(r'%(?:\d+\$)?[sd]|%%')
SYMBOLS = ['▶', '■', '●', '→', '·', '…', '×', '±', '∞']
# Right-to-left languages: the arrow glyph is not mirrored by the text layout, so the build writes ← where the English has →.
RTL_TAGS = {'ar', 'he', 'fa', 'ur', 'ps', 'sd', 'ug'}
# soft length limits (characters) for labels that must fit on small buttons; exceeding them is only a warning
LIMITS = [
    (re.compile(r'^bar_(mode_|stopped|get_ready|paused|rec$)'), 12),
    (re.compile(r'^(ok|cancel|save|close|delete|copy|dismiss|share|start)$'), 16),
    (re.compile(r'^(unit_min|unit_s)$'), 6),
    (re.compile(r'^(speed_|size_|theme_|style_|row_default|btn_)'), 22),
    (re.compile(r'^(state_)'), 26),
    (re.compile(r'^(ov_mode_record|ov_mode_start)$'), 24),
]


def languages():
    """[(tag, name, qualifier)] from tools/languages.tsv (every language that is meant to be supported)"""
    out = []
    with open(MASTER, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n').rstrip('\r')
            if not line.strip() or line.startswith('#'):
                continue
            parts = line.split('\t')
            tag, name = parts[0], parts[1]
            q = parts[2] if len(parts) > 2 else tag
            out.append((tag, name, q))
    return out


def has_strings(qualifier):
    return qualifier == '' or os.path.exists(os.path.join(RES, 'values-' + qualifier, 'strings.xml'))


def read_source():
    """
    Parse the English strings.xml: [(key, text, note)] in file order, translatable strings only.
    A comment in front of a string is its note. A comment that starts with [group] is a note for that string and
    for the strings after it whose key starts with the same word (bar_..., step_...), up to the next blank line.
    """
    raw = open(SRC_XML, encoding='utf-8').read()
    items = []
    own = ''
    pending_group = None
    group_note, group_prefix = '', ''
    tok = re.compile(r'<!--(.*?)-->|<string\s+([^>]*)>(.*?)</string>|\n[ \t]*\n', re.S)
    for m in tok.finditer(raw):
        if m.group(1) is not None:
            c = ' '.join(m.group(1).split())
            if c.startswith('====') or c.startswith('Mareco: every text'):
                continue
            if c.startswith('[group]'):
                pending_group = c[len('[group]'):].strip()
            else:
                own = c
            continue
        if m.group(2) is None:  # blank line: a new section
            own = ''
            group_note, group_prefix = '', ''
            continue
        attrs = m.group(2)
        name = re.search(r'name="([^"]+)"', attrs).group(1)
        prefix = name.split('_')[0]
        if pending_group is not None:
            group_note, group_prefix = pending_group, prefix
            pending_group = None
        elif prefix != group_prefix:
            group_note, group_prefix = '', ''
        note = ' '.join(x for x in (own, group_note) if x)
        own = ''
        if 'translatable="false"' in attrs:
            continue
        items.append((name, unescape_xml_text(m.group(3)), note))
    return items


def unescape_xml_text(body):
    """Text as a translator sees it: XML entities resolved, \\n kept as the two characters backslash-n."""
    t = body.replace('&amp;', '&').replace('&lt;', '<').replace('&gt;', '>')
    t = t.replace("\\'", "'").replace('\\"', '"').replace('\\@', '@').replace('\\?', '?')
    return t


def escape_for_xml(t):
    """Translator text -> text for an Android string resource."""
    out = []
    i = 0
    while i < len(t):
        ch = t[i]
        if ch == '\\' and i + 1 < len(t):
            out.append(ch + t[i + 1])  # \n, \', \", \uXXXX stay as written
            i += 2
            continue
        if ch == '&':
            m = re.match(r'&(amp|lt|gt|quot|apos|#\d+|#x[0-9a-fA-F]+);', t[i:])
            if m:
                out.append(m.group(0))
                i += len(m.group(0))
                continue
            out.append('&amp;')
        elif ch == '<':
            out.append('&lt;')
        elif ch == '>':
            out.append('&gt;')
        elif ch == "'":
            out.append("\\'")
        elif ch == '"':
            out.append('\\"')
        else:
            out.append(ch)
        i += 1
    s = ''.join(out)
    if s[:1] in ('@', '?'):
        s = '\\' + s
    return s


def placeholders(t):
    """Normalised placeholder list, e.g. ['%1$s', '%2$s'] (a lone %s counts as %1$s)."""
    found = PLACEHOLDER.findall(t)
    plain = [p for p in found if p not in ('%%',)]
    pct = [p for p in found if p == '%%']
    norm = []
    n = 0
    for p in plain:
        if '$' in p:
            norm.append(p)
        else:
            n += 1
            norm.append('%%%d$%s' % (n, p[-1]))
    return sorted(norm), len(pct)


def check_pair(key, en, tr, rtl=False):
    """(errors, warnings) for one translated string."""
    errors, warnings = [], []
    if not tr.strip():
        return ['empty translation'], warnings
    if '\t' in tr or '\n' in tr:
        errors.append('contains a real tab/newline (use \\n)')
    pe, pcte = placeholders(en)
    pt, pctt = placeholders(tr)
    if pe != pt:
        errors.append('placeholders differ: English %s, translation %s' % (pe or 'none', pt or 'none'))
    if pcte != pctt:
        errors.append('literal %% signs differ (English %d, translation %d)' % (pcte, pctt))
    # a lone % that is not a placeholder breaks String.format
    stripped = PLACEHOLDER.sub('', tr)
    if '%' in stripped:
        errors.append('stray % sign (write %% for a percent sign)')
    if en.count('\\n') != tr.count('\\n'):
        errors.append('number of \\n differs (English %d, translation %d)' % (en.count('\\n'), tr.count('\\n')))
    for sym in SYMBOLS:
        have = tr.count(sym) + (tr.count('←') if (rtl and sym == '→') else 0)
        if en.count(sym) > have:
            warnings.append('symbol %s missing' % sym)
    for rx, limit in LIMITS:
        if rx.search(key) and len(tr) > limit:
            warnings.append('long for a small button: %d characters (aim for <= %d)' % (len(tr), limit))
            break
    if tr.strip() == en.strip() and len(en) > 24 and not re.fullmatch(r'[\W\d]*', en):
        warnings.append('identical to the English text')
    return errors, warnings


def cmd_source(a):
    items = read_source()
    os.makedirs(a.work, exist_ok=True)
    with open(os.path.join(a.work, 'source.tsv'), 'w', encoding='utf-8') as f:
        for i, (k, t, n) in enumerate(items, 1):
            f.write('%d\t%s\t%s\t%s\n' % (i, k, t, n))
    print('wrote %d strings to %s' % (len(items), os.path.join(a.work, 'source.tsv')))


def read_tsv(path):
    rows = {}
    with open(path, encoding='utf-8') as f:
        for ln, line in enumerate(f, 1):
            line = line.rstrip('\n').rstrip('\r')
            if not line.strip():
                continue
            parts = line.split('\t')
            if len(parts) < 2 or not parts[0].strip().isdigit():
                raise ValueError('line %d: expected "<number><TAB><translation>"' % ln)
            n = int(parts[0])
            if n in rows:
                raise ValueError('line %d: number %d appears twice' % (ln, n))
            rows[n] = '\t'.join(parts[1:]).strip()
    return rows


def check_file(tag, work, quiet=False):
    items = read_source()
    path = os.path.join(work, 'out', tag + '.tsv')
    if not os.path.exists(path):
        print('%s: file not found: %s' % (tag, path))
        return None
    try:
        rows = read_tsv(path)
    except ValueError as e:
        print('%s: %s' % (tag, e))
        return None
    bad = 0
    warn = 0
    for i, (k, en, note) in enumerate(items, 1):
        if i not in rows:
            print('%s: MISSING %d (%s)' % (tag, i, k))
            bad += 1
            continue
        errors, warnings = check_pair(k, en, rows[i], rtl=tag in RTL_TAGS)
        for e in errors:
            print('%s: ERROR %d (%s): %s | %s' % (tag, i, k, e, rows[i][:70]))
            bad += 1
        if not quiet:
            for w in warnings:
                print('%s: warning %d (%s): %s | %s' % (tag, i, k, w, rows[i][:50]))
        warn += len(warnings)
    extra = sorted(set(rows) - set(range(1, len(items) + 1)))
    for n in extra:
        print('%s: EXTRA number %d' % (tag, n))
        bad += 1
    print('%s: %s (%d strings, %d errors, %d warnings)' % (tag, 'OK' if bad == 0 else 'FAILED', len(items), bad, warn))
    return rows if bad == 0 else None


def write_xml(tag, qualifier, rows):  # tag decides the arrow direction
    items = read_source()
    folder = os.path.join(RES, 'values-' + qualifier)
    os.makedirs(folder, exist_ok=True)
    lines = ['<?xml version="1.0" encoding="utf-8"?>', '<resources>']
    for i, (k, en, note) in enumerate(items, 1):
        text = rows[i].replace('→', '←') if tag in RTL_TAGS else rows[i]
        lines.append('    <string name="%s">%s</string>' % (k, escape_for_xml(text)))
    lines.append('</resources>')
    path = os.path.join(folder, 'strings.xml')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    ET.parse(path)  # well-formed?
    return path


def selected(a):
    langs = [l for l in languages() if l[0] != 'en']
    if a.tag == 'all':
        return langs
    pick = [l for l in langs if l[0] == a.tag]
    if not pick:
        sys.exit('unknown language tag %s' % a.tag)
    return pick


def cmd_check(a):
    ok = True
    for tag, name, q in selected(a):
        if check_file(tag, a.work, quiet=a.quiet) is None:
            ok = False
    sys.exit(0 if ok else 1)


def cmd_build(a):
    ok = True
    pending = []
    for tag, name, q in selected(a):
        if a.tag == 'all' and not os.path.exists(os.path.join(a.work, 'out', tag + '.tsv')):
            pending.append(tag)  # not translated yet: not an error when building everything
            continue
        rows = check_file(tag, a.work, quiet=True)
        if rows is None:
            ok = False
            continue
        print('  wrote', os.path.relpath(write_xml(tag, q, rows), ROOT))
    if pending:
        print('not translated yet (%d): %s' % (len(pending), ' '.join(pending)))
    sys.exit(0 if ok else 1)


def parse_values(path):
    root = ET.parse(path).getroot()
    d = {}
    for e in root.findall('string'):
        d[e.get('name')] = (e.text or '')
    return d


def cmd_audit(a):
    items = read_source()
    keys = [k for k, _, _ in items]
    en = {k: t for k, t, _ in items}
    missing_dirs, problems = [], 0
    for tag, name, q in languages():
        if tag == 'en':
            continue
        p = os.path.join(RES, 'values-' + q, 'strings.xml')
        if not os.path.exists(p):
            missing_dirs.append(tag)
            continue
        try:
            d = parse_values(p)
        except ET.ParseError as e:
            print('%s: not well-formed XML: %s' % (tag, e))
            problems += 1
            continue
        for k in keys:
            if k not in d:
                print('%s: missing %s' % (tag, k))
                problems += 1
                continue
            # compare placeholders on the resolved text (aapt2 turns \\n into a real newline; compare via counts)
            pe, pcte = placeholders(en[k])
            pt, pctt = placeholders(d[k])
            if pe != pt or pcte != pctt:
                print('%s: %s placeholders differ' % (tag, k))
                problems += 1
        for k in d:
            if k not in en:
                print('%s: unknown key %s' % (tag, k))
                problems += 1
    print('languages without a strings.xml: %d %s' % (len(missing_dirs), ' '.join(missing_dirs)))
    print('audit problems: %d' % problems)
    sys.exit(1 if (problems or missing_dirs) else 0)


def kt_string(t):
    return '"' + t.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$') + '"'


def cmd_sync(a):
    """Languages.kt and locales_config.xml list exactly the languages that have a translation."""
    have = [(t, n, q) for (t, n, q) in languages() if t == 'en' or has_strings(q)]
    lost = [t for (t, n, q) in languages() if not any(h[0] == t for h in have)]
    kt = open(LANGS_KT, encoding='utf-8').read()
    i, j = kt.index(KT_BEGIN), kt.index(KT_END)
    lines = []
    for (t, n, q) in have:
        if q == t:
            lines.append('        Language(%s, %s)' % (kt_string(t), kt_string(n)))
        else:
            lines.append('        Language(%s, %s, %s)' % (kt_string(t), kt_string(n), kt_string(q)))
    block = KT_BEGIN + '\n' + ',\n'.join(lines) + '\n'
    open(LANGS_KT, 'w', encoding='utf-8').write(kt[:i] + block + kt[j:])
    xml = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- The languages Mareco is translated into (Android 13+ shows them under Settings > Apps > Mareco > Language). -->',
           '<!-- Generated by tools/i18n.py sync, together with the list in Languages.kt (the unit test StringsTest checks that). -->',
           '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">']
    xml += ['    <locale android:name="%s" />' % t for (t, n, q) in have]
    xml.append('</locale-config>')
    open(LOCALES_XML, 'w', encoding='utf-8').write('\n'.join(xml) + '\n')
    print('sync: %d languages in the app (%s)' % (len(have), ' '.join(t for t, n, q in have)))
    print('      %d planned languages without a translation yet: %s' % (len(lost), ' '.join(lost) or '-'))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--work', default=os.path.join(ROOT, 'tools', 'work'), help='folder with source.tsv and out/<tag>.tsv')
    sub = ap.add_subparsers(dest='cmd', required=True)
    sub.add_parser('source').set_defaults(f=cmd_source)
    for name, f in (('check', cmd_check), ('build', cmd_build)):
        s = sub.add_parser(name)
        s.add_argument('tag', help='language tag from Languages.kt, or "all"')
        s.add_argument('--quiet', action='store_true', help='hide warnings')
        s.set_defaults(f=f)
    sub.add_parser('audit').set_defaults(f=cmd_audit)
    sub.add_parser('sync').set_defaults(f=cmd_sync)
    a = ap.parse_args()
    a.f(a)


if __name__ == '__main__':
    main()
